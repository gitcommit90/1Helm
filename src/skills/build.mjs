// node src/skills/build.mjs [--check]
// Regenerates src/skills/bundle.js: one static import per skill file (SKILL.md, references/**/*.md, scripts/**/*), so the Worker
// bundles them as text (wrangler "Text" rules: **/*.md, and **/skills/*/scripts/* for scripts; the node tests load both through
// test/stubs/register.mjs). Run it after adding, renaming or removing any skill file. --check exits 1 when bundle.js is stale.
// Specifiers are written as "../skills/<slug>/…" (same folder, one hop up and back) so the scripts rule's glob can't match any
// other import in the Worker or its packages.
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function walk(dir, rel = "") {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).sort().flatMap((n) => {
    if (n.startsWith(".")) return [];
    const p = join(dir, n), r = rel ? `${rel}/${n}` : n;
    return statSync(p).isDirectory() ? walk(p, r) : [r];
  });
}
// Keep the public skill key stable when a Cloud-only skill moves under ee/.
// The source path changes; read_skill and the computer still see the same slug.
function skillEntries(dir = HERE) {
  const out = [];
  const seen = new Set();
  for (const [base, prefix] of [[dir, ""], [join(dir, "ee"), "ee/"]]) {
    if (!existsSync(base)) continue;
    for (const slug of readdirSync(base).sort()) {
      const d = join(base, slug);
      if (!statSync(d).isDirectory() || !existsSync(join(d, "SKILL.md"))) continue;
      if (seen.has(slug)) throw new Error(`Duplicate skill: ${slug}`);
      seen.add(slug);
      const add = (path) => out.push({ key: `${slug}/${path}`, source: `${prefix}${slug}/${path}` });
      add("SKILL.md");
      for (const f of walk(join(d, "references"))) if (f.endsWith(".md")) add(`references/${f}`);
      for (const f of walk(join(d, "scripts"))) add(`scripts/${f}`);
    }
  }
  return out.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
}
// Every bundled logical file, as "<slug>/<path>", sorted.
export function skillFiles(dir = HERE) { return skillEntries(dir).map((entry) => entry.key); }
export function bundleSource(dir = HERE) {
  const files = skillEntries(dir);
  const L = ["// GENERATED by `node src/skills/build.mjs` from src/skills/<slug>/ (SKILL.md, references/, scripts/). Never edit by hand.",
    ...files.map((f, i) => `import f${i} from ${JSON.stringify(`../skills/${f.source}`)};`),
    "export const FILES = {", ...files.map((f, i) => `  ${JSON.stringify(f.key)}: f${i},`), "};", ""];
  return L.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = bundleSource(), path = join(HERE, "bundle.js"), have = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (process.argv.includes("--check")) { if (want !== have) { console.error("src/skills/bundle.js is stale: run node src/skills/build.mjs"); process.exit(1); } console.log("bundle.js is current"); }
  else { writeFileSync(path, want); console.log(`bundle.js: ${skillFiles().length} files`); }
}
